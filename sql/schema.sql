values ('gallery', 'gallery', true)
on conflict (id) do update set public = true;

insert into storage.buckets (id, name, public)
values ('documents', 'documents', true)
on conflict (id) do update set public = true;

-- Remove previous storage policies for these buckets, then recreate.
do $$
declare r record;
begin
  for r in
    select policyname from pg_policies
    where schemaname = 'storage'
      and tablename = 'objects'
      and policyname like 'bca %'
  loop
    execute format('drop policy %I on storage.objects', r.policyname);
  end loop;
end $$;

create policy "bca public read storage"
  on storage.objects for select
  using (bucket_id in ('gallery', 'documents'));

create policy "bca admin insert storage"
  on storage.objects for insert to authenticated
  with check (
    bucket_id in ('gallery', 'documents')
    and public.admin_role() is not null
  );

create policy "bca admin update storage"
  on storage.objects for update to authenticated
  using (
    bucket_id in ('gallery', 'documents')
    and public.admin_role() is not null
  );

create policy "bca admin delete storage"
  on storage.objects for delete to authenticated
  using (
    bucket_id in ('gallery', 'documents')
    and public.admin_role() is not null
  );

